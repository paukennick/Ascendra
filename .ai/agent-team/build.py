#!/usr/bin/env python3
"""Render the Senior Engineering Agent team into per-platform editions.

One canonical role definition in roles/ produces two incompatible outputs:
Claude Code subagents (.claude/agents/) and Anthropic Managed Agents
definitions consumed by `ant apply`. Skills are shared verbatim and are
never generated.

Standard library only, so this can run as an omni step without adding a
dependency to any project that adopts it.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ROLES_DIR = ROOT / "roles"
SKILLS_DIR = ROOT / "skills"
DIST = ROOT / "dist"
CC_OUT = DIST / "claude-code" / "agents"
MA_OUT = DIST / "managed-agents" / "agents"
CAPS_DOC = ROOT / "docs" / "capabilities.md"

TOOLSET = "agent_toolset_20260401"

# Capability vocabulary -> platform tool names. Adding a capability here is
# the only place a new tool needs to be taught to both editions.
CLAUDE_TOOLS = {
    "read": ["Read"],
    "search": ["Glob", "Grep"],
    "execute": ["Bash"],
    "write": ["Write", "Edit"],
    "web": ["WebSearch", "WebFetch"],
}
MANAGED_TOOLS = {
    "read": ["read"],
    "search": ["glob", "grep"],
    "execute": ["bash"],
    "write": ["write", "edit"],
    "web": ["web_search", "web_fetch"],
}
# Tools whose calls are evaluated per-call rather than auto-approved.
GUARDED = {"bash", "write", "edit"}

TIERS = {
    "lead": {"managed_model": "claude-opus-5", "claude_model": "opus", "max_turns": 80},
    "standard": {"managed_model": "claude-sonnet-5", "claude_model": "sonnet", "max_turns": 60},
}

BANNER = "# GENERATED by build.py from roles/{slug}.md -- do not edit by hand"


class RoleError(RuntimeError):
    pass


def parse_frontmatter(text: str) -> tuple[dict, str]:
    """Minimal frontmatter reader: `key: value` and `key: [a, b]` only."""
    if not text.startswith("---"):
        raise RoleError("file does not start with frontmatter")
    _, raw, body = text.split("---", 2)
    data: dict = {}
    for line in raw.strip().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            raise RoleError(f"unparsable frontmatter line: {line!r}")
        key, _, value = line.partition(":")
        key, value = key.strip(), value.strip()
        if value.startswith("[") and value.endswith("]"):
            inner = value[1:-1].strip()
            data[key] = [p.strip() for p in inner.split(",") if p.strip()]
        else:
            data[key] = value
    return data, body.strip()


def load_roles() -> list[dict]:
    roles = []
    for path in sorted(ROLES_DIR.glob("*.md")):
        try:
            meta, body = parse_frontmatter(path.read_text(encoding="utf-8"))
        except RoleError as exc:
            raise RoleError(f"{path.name}: {exc}") from exc
        for required in ("slug", "title", "description", "tier", "capabilities"):
            if required not in meta:
                raise RoleError(f"{path.name}: missing required key {required!r}")
        if meta["slug"] != path.stem:
            raise RoleError(f"{path.name}: slug {meta['slug']!r} does not match filename")
        if meta["tier"] not in TIERS:
            raise RoleError(f"{path.name}: unknown tier {meta['tier']!r}")
        for cap in meta["capabilities"]:
            if cap not in CLAUDE_TOOLS:
                raise RoleError(f"{path.name}: unknown capability {cap!r}")
        if not body:
            raise RoleError(f"{path.name}: empty body (no system prompt)")
        meta["body"] = body
        meta.setdefault("skills", [])
        meta.setdefault("delegates", [])
        meta.setdefault("effort", "high")
        roles.append(meta)
    if not roles:
        raise RoleError(f"no role files found in {ROLES_DIR}")
    known = {r["slug"] for r in roles}
    for role in roles:
        for target in role["delegates"]:
            if target not in known:
                raise RoleError(f"{role['slug']}: delegates to unknown role {target!r}")
    return roles


def render_claude_code(role: dict) -> str:
    tier = TIERS[role["tier"]]
    tools: list[str] = []
    for cap in role["capabilities"]:
        tools.extend(CLAUDE_TOOLS[cap])
    if role["delegates"]:
        tools.append("Agent(" + ", ".join(role["delegates"]) + ")")
    lines = [
        "---",
        BANNER.format(slug=role["slug"]),
        f"name: {role['slug']}",
        f"description: {role['description']}",
        "tools: " + ", ".join(tools),
        f"model: {tier['claude_model']}",
        f"effort: {role['effort']}",
        "permissionMode: default",
        f"maxTurns: {tier['max_turns']}",
    ]
    if role["skills"]:
        lines.append("skills:")
        lines.extend(f"  - {s}" for s in role["skills"])
    lines += ["---", "", role["body"], ""]
    return "\n".join(lines)


def render_managed(role: dict) -> str:
    tier = TIERS[role["tier"]]
    names: list[str] = []
    for cap in role["capabilities"]:
        names.extend(MANAGED_TOOLS[cap])
    lines = [
        "---",
        BANNER.format(slug=role["slug"]),
        f"name: {role['title']}",
        f"description: {role['description']}",
        "model:",
        f"  id: {tier['managed_model']}",
        f"  effort: {role['effort']}",
        "tools:",
        f"  - type: {TOOLSET}",
        "    default_config:",
        "      enabled: false",
        "    configs:",
    ]
    for name in names:
        lines.append(f"      - name: {name}")
        lines.append("        enabled: true")
        if name in GUARDED:
            lines.append("        permission_policy:")
            lines.append("          type: auto")
    if role["delegates"]:
        lines += ["multiagent:", "  type: coordinator", "  agents:"]
        lines.extend(f"    - ./{d}.md" for d in role["delegates"])
    lines += [
        "metadata:",
        "  package: senior-engineering-agent",
        "  edition: anthropic-managed-agents",
        f"  role: {role['slug']}",
        "---",
        "",
        role["body"],
        "",
    ]
    return "\n".join(lines)


def render_capabilities(roles: list[dict]) -> str:
    """The authorization matrix, generated so it cannot drift from the roles."""
    head = [
        "<!-- GENERATED by build.py from roles/ -- do not edit by hand -->",
        "",
        "# Capabilities",
        "",
        "What each role may do, derived from its `capabilities:` list. `write` implies",
        "editing files inside the shared workspace only; no role may mutate an external",
        "system without the explicit authorization described in [Authorization](#authorization).",
        "",
        "| Role | Model | Read | Search | Execute | Write | Delegates | Skills |",
        "| --- | --- | :-: | :-: | :-: | :-: | --- | --- |",
    ]
    for role in roles:
        tier = TIERS[role["tier"]]
        mark = lambda cap: "yes" if cap in role["capabilities"] else "no"
        delegates = str(len(role["delegates"])) if role["delegates"] else "-"
        skills = ", ".join(f"`{s}`" for s in role["skills"]) or "-"
        head.append(
            f"| `{role['slug']}` | {tier['managed_model']} | {mark('read')} | {mark('search')} "
            f"| {mark('execute')} | {mark('write')} | {delegates} | {skills} |"
        )
    head += [
        "",
        "## Read-only roles",
        "",
        "The reviewers cannot write. That is enforced by the generated tool lists in both",
        "editions, not by instruction alone: `write` and `edit` are absent from the Managed",
        "Agents toolset config, and `Write`/`Edit` are absent from the Claude Code `tools`",
        "line. A reviewer that wants a change describes it; an implementer makes it.",
        "",
        "## Shared filesystem",
        "",
        "Every member of a Managed Agents session works in the same sandbox. Two roles",
        "editing the same file will clobber each other, so the coordinator assigns",
        "overlapping implementation work to exactly one primary implementer.",
        "",
        "## Authorization",
        "",
        "Execute and write calls carry `permission_policy: {type: auto}` in the Managed",
        "Agents edition, which lets the service allow, deny, or pause each call on risk",
        "rather than approving everything in advance. Web tools are off for every role.",
        "",
        "No role mutates source control, CI/CD, cloud, cluster, database, or production",
        "state on its own. A change to an external system is presented as a packet -- exact",
        "target and operation, expected effect, blast radius, rollback, post-change",
        "validation -- and waits for explicit authorization for that specific action.",
        "",
        "## Final status vocabulary",
        "",
        "Work ends in exactly one of: **Verified within stated scope**, **Conditionally",
        "acceptable**, **Changes required**, **Blocked**. The package never claims software",
        "is fully secure, bug-free, unbreakable, or completely optimized.",
        "",
    ]
    return "\n".join(head)


def rendered(roles: list[dict]) -> dict[Path, str]:
    out: dict[Path, str] = {}
    for role in roles:
        out[CC_OUT / f"{role['slug']}.md"] = render_claude_code(role)
        out[MA_OUT / f"{role['slug']}.md"] = render_managed(role)
    out[CAPS_DOC] = render_capabilities(roles)
    return out


def cmd_build(_args) -> int:
    roles = load_roles()
    files = rendered(roles)
    for directory in (CC_OUT, MA_OUT, CAPS_DOC.parent):
        directory.mkdir(parents=True, exist_ok=True)
    stale = {p for d in (CC_OUT, MA_OUT) for p in d.glob("*.md")} - set(files)
    for path in sorted(stale):
        path.unlink()
        print(f"removed {path.relative_to(ROOT)}")
    for path, text in sorted(files.items()):
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"rendered {len(roles)} roles into {len(files)} files")
    return 0


def cmd_doctor(_args) -> int:
    roles = load_roles()
    problems = []
    for path, text in sorted(rendered(roles).items()):
        rel = path.relative_to(ROOT)
        if not path.exists():
            problems.append(f"missing generated file: {rel}")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"stale generated file: {rel}")
    for role in roles:
        for skill in role["skills"]:
            if not (SKILLS_DIR / skill / "SKILL.md").is_file():
                problems.append(f"{role['slug']}: skill {skill!r} has no SKILL.md")
    if problems:
        for problem in problems:
            print(f"drift: {problem}", file=sys.stderr)
        print(f"{len(problems)} problem(s); run `python build.py build`", file=sys.stderr)
        return 1
    print(f"clean: {len(roles)} roles, both editions current")
    return 0


def cmd_install(args) -> int:
    target = Path(args.target).expanduser().resolve()
    if not target.is_dir():
        print(f"not a directory: {target}", file=sys.stderr)
        return 1
    if cmd_doctor(args) != 0:
        return 1
    pairs = [
        (CC_OUT, target / ".claude" / "agents"),
        (SKILLS_DIR, target / ".claude" / "skills"),
    ]
    if args.managed:
        pairs.append((MA_OUT, target / "managed-agents" / "agents"))
    for src, dst in pairs:
        dst.mkdir(parents=True, exist_ok=True)
        shutil.copytree(src, dst, dirs_exist_ok=True)
        print(f"installed {src.relative_to(ROOT)} -> {dst}")
    print("note: existing files at those paths were overwritten; skills are shared, not generated")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="build.py", description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("build", help="render both editions into dist/")
    sub.add_parser("doctor", help="fail if dist/ is stale or a skill is missing")
    install = sub.add_parser("install", help="copy the rendered team into a project")
    install.add_argument("target", help="path to the project repository")
    install.add_argument(
        "--managed",
        action="store_true",
        help="also install managed-agents/agents/ for `ant apply`",
    )
    args = parser.parse_args(argv)
    handler = {"build": cmd_build, "doctor": cmd_doctor, "install": cmd_install}[args.command]
    try:
        return handler(args)
    except RoleError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
