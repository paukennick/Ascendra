// REQ-141 (docs/sims.md 5.8): the engine's source of truth is
// backend/lib/sim/engine/; the app runs a generated copy in
// mobile/src/sim/engine/ (`npm run sim:sync-engine`). The drift test and the
// sync script both build the copy from here, so they can't disagree.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";
import { join, posix, relative, sep } from "node:path";

export const ENGINE_SOURCE_DIR = join(__dirname, "engine");
export const ENGINE_COPY_DIR = join(__dirname, "..", "..", "..", "mobile", "src", "sim", "engine");

const HEADER_PREFIX = "// Generated by `npm run sim:sync-engine` (backend) from backend/lib/sim/engine/";

// Engine unit tests stay in the backend; the app copy carries only the engine.
export function isEngineFile(name: string): boolean {
  return name.endsWith(".ts") && !name.endsWith(".test.ts");
}

// Relative paths with "/" separators, sorted, so results match on every OS.
export function listFiles(root: string, include: (name: string) => boolean = () => true): string[] {
  const out: string[] = [];
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (include(entry.name)) out.push(relative(root, full).split(sep).join("/"));
    }
  };
  walk(root);
  return out.sort();
}

export function sha256(text: string): string {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

export function copyOf(relPath: string, source: string): string {
  return `${HEADER_PREFIX}${relPath} (sha256 ${sha256(source)}). Do not edit: change the source and re-run.\n${source}`;
}

// Map of relative path -> the exact bytes the mobile copy must hold.
export function expectedCopy(sourceDir: string = ENGINE_SOURCE_DIR): Map<string, string> {
  const files = new Map<string, string>();
  for (const rel of listFiles(sourceDir, isEngineFile)) {
    files.set(rel, copyOf(rel, readFileSync(join(sourceDir, rel), "utf8")));
  }
  return files;
}

// The constraints that let one source run under tsx, Node's type stripping
// and Metro (5.8): relative imports only, with `.ts`, staying inside the
// engine major's own folder (engine/v1/...). Returns one message per breach.
export function importViolations(relPath: string, source: string): string[] {
  const problems: string[] = [];
  const major = relPath.split("/")[0];
  const specifiers = [
    ...source.matchAll(/\b(?:import|export)\b[^'"`;]*?\bfrom\s*["']([^"']+)["']/g),
    ...source.matchAll(/\bimport\s*["']([^"']+)["']/g),
    ...source.matchAll(/\bimport\s*\(\s*["']([^"']+)["']\s*\)/g),
  ].map((m) => m[1]);
  for (const spec of specifiers) {
    if (!spec.startsWith("./") && !spec.startsWith("../")) {
      problems.push(`${relPath}: imports "${spec}"; the engine may only import its own files`);
      continue;
    }
    if (!spec.endsWith(".ts")) problems.push(`${relPath}: import "${spec}" needs the .ts extension`);
    const target = posix.normalize(posix.join(posix.dirname(relPath), spec));
    if (target.startsWith("../") || target.split("/")[0] !== major) {
      problems.push(`${relPath}: import "${spec}" leaves engine/${major}/`);
    }
  }
  return problems;
}
