// REQ-141 (docs/sims.md 5.8): the app's engine copy loads under Node's own
// type stripping, the same erasable-syntax rule Metro and tsx share. The copy
// is generated (backend: `npm run sim:sync-engine`); the backend drift test
// checks its bytes, this checks it runs here.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ENGINE_MAJOR } from "./engine/v1/index.ts";

test("engine v1 copy loads and is the generated copy", () => {
  assert.equal(ENGINE_MAJOR, 1);
  const first = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "engine", "v1", "index.ts"), "utf8").split("\n")[0];
  assert.match(first, /^\/\/ Generated by `npm run sim:sync-engine` .* \(sha256 [0-9a-f]{64}\)\./);
});
